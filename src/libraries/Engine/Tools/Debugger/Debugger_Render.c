void dbg_draw_rect(float x, float y, float w, float h, float r, float g, float b, float a) {
    glColor4f(r, g, b, a);
    glBegin(GL_QUADS);
        glVertex2f(x, y);
        glVertex2f(x + w, y);
        glVertex2f(x + w, y + h);
        glVertex2f(x, y + h);
    glEnd();
}

void dbg_draw_rect_outline(float x, float y, float w, float h, float lw, float r, float g, float b, float a) {
    glColor4f(r, g, b, a);
    glLineWidth(lw);
    glBegin(GL_LINE_LOOP);
        glVertex2f(x, y);
        glVertex2f(x + w, y);
        glVertex2f(x + w, y + h);
        glVertex2f(x, y + h);
    glEnd();
}

void dbg_draw_line(float x1, float y1, float x2, float y2, float lw, float r, float g, float b, float a) {
    glColor4f(r, g, b, a);
    glLineWidth(lw);
    glBegin(GL_LINES);
        glVertex2f(x1, y1);
        glVertex2f(x2, y2);
    glEnd();
}

void dbg_draw_triangle(float x1, float y1, float x2, float y2, float x3, float y3, float r, float g, float b, float a) {
    glColor4f(r, g, b, a);
    glBegin(GL_TRIANGLES);
        glVertex2f(x1, y1);
        glVertex2f(x2, y2);
        glVertex2f(x3, y3);
    glEnd();
}

void dbg_draw_circle(float cx, float cy, float radius, float r, float g, float b, float a) {
    glColor4f(r, g, b, a);
    glBegin(GL_TRIANGLE_FAN);
        glVertex2f(cx, cy);
        for (int i = 0; i <= 20; i++) {
            float theta = (float)i * 2.0f * 3.14159265f / 20.0f;
            glVertex2f(cx + cosf(theta) * radius, cy + sinf(theta) * radius);
        }
    glEnd();
}

void dbg_draw_char(float x, float y, char c, float r, float g, float b, float scale) {
    unsigned char uc = (unsigned char)c;
    if (uc < 32 || uc > 126) uc = '?';
    const unsigned char *glyph = dbg_font5x7[uc - 32];

    glColor4f(r, g, b, 1.0f);
    glBegin(GL_QUADS);
    for (int col = 0; col < 5; col++) {
        unsigned char col_bits = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (col_bits & (1 << row)) {
                float px = x + (float)col * scale;
                float py = y + (float)row * scale;
                glVertex2f(px, py);
                glVertex2f(px + scale, py);
                glVertex2f(px + scale, py + scale);
                glVertex2f(px, py + scale);
            }
        }
    }
    glEnd();
}

void dbg_draw_text(float x, float y, const char *str, float r, float g, float b, float scale) {
    if (!str) return;
    float cur_x = x;
    for (int i = 0; str[i] != '\0'; i++) {
        dbg_draw_char(cur_x, y, str[i], r, g, b, scale);
        cur_x += 6.0f * scale;
    }
}

int dbg_button(float x, float y, float w, float h, const char *text, float accent_r, float accent_g, float accent_b) {
    int hover = (g_dbg.mouse_x >= x && g_dbg.mouse_x <= x + w && g_dbg.mouse_y >= y && g_dbg.mouse_y <= y + h);
    float bg_r = hover ? 0.22f : 0.16f;
    float bg_g = hover ? 0.22f : 0.16f;
    float bg_b = hover ? 0.25f : 0.18f;

    dbg_draw_rect(x, y, w, h, bg_r, bg_g, bg_b, 1.0f);
    dbg_draw_rect(x, y + h - 2.0f, w, 2.0f, accent_r, accent_g, accent_b, 1.0f);
    dbg_draw_rect_outline(x, y, w, h, 1.0f, 0.3f, 0.3f, 0.35f, 1.0f);

    float text_x = x + (w - (float)strlen(text) * 7.5f) * 0.5f;
    float text_y = y + (h - 10.0f) * 0.5f;
    dbg_draw_text(text_x, text_y, text, hover ? 1.0f : 0.9f, hover ? 1.0f : 0.9f, hover ? 1.0f : 0.9f, 1.25f);

    return hover && g_dbg.mouse_left_pressed;
}

